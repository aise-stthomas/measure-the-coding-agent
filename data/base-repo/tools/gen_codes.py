"""Write src/generated/codes.py from data/codes.csv. Run: python tools/gen_codes.py"""
import csv, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render(rows):
    lines = ['"""Generated by tools/gen_codes.py from data/codes.csv. Do not edit."""', "", "CODES = {"]
    lines += [f'    "{r["code"].strip().upper()}": {int(r["percent"])},' for r in rows]
    return "\n".join(lines + ["}", ""])


def main():
    with open(os.path.join(ROOT, "data", "codes.csv")) as f:
        rows = list(csv.DictReader(f))
    with open(os.path.join(ROOT, "src", "generated", "codes.py"), "w") as f:
        f.write(render(rows))
    print(f"wrote {len(rows)} codes to src/generated/codes.py")


if __name__ == "__main__":
    main()
